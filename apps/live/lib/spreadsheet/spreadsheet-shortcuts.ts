// The spreadsheet's keyboard shortcuts (docs/specs/029-sheets/keyboard-shortcuts.md): every one of Google's, for PC,
// Mac and ChromeOS, one row per action in the notation. A test reads the spec's tables and fails on any difference,
// so this file and the spec say the same thing. A `surface` row is heard by the grid, the area cycle or the editor's
// history keys themselves: listed and shown beside its item, never run by the shell's layer.
import type { ShortcutRow, ShortcutStatus } from '@/lib/office/shortcut-registry';

function row(
  id: string,
  group: string,
  action: string,
  pc: string,
  mac: string,
  chromeos: string,
  status: ShortcutStatus,
): ShortcutRow {
  return { id, group, action, keys: { pc, mac, chromeos }, status };
}

