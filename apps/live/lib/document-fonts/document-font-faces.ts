// The served document fonts' faces as one stylesheet (docs/specs/004-interface-design/fonts.md "Served from LiveDoc"):
// each served family's regular, italic, bold and bold italic, Latin and Latin Extended subsets, WOFF2, from its
// Fontsource package. Fontsource's own stylesheets carry every subset and a WOFF fallback; this keeps the two subsets,
// each with its unicode range, so a browser downloads only the files the text uses. Pure: the caller reads the files.
import type { DocumentFont, DocumentFontStyle } from '@livedoc/document';

/** The subsets served; Fontsource names each face `<id>-<subset>-<weight>-<style>`. */
export const DOCUMENT_FONT_SUBSETS = ['latin-ext', 'latin'] as const;

/** Where the stylesheet finds the packages' files, relative to itself. */
export const DOCUMENT_FONT_FILES = '../node_modules/@fontsource';

const sheetOf = (style: DocumentFontStyle) =>
  style.endsWith('-normal') ? `${style.slice(0, 3)}.css` : `${style}.css`;

/** One face's unicode range in its package's stylesheet, or null when the stylesheet has no such face. */
function faceRange(sheet: string, face: string): string | null | undefined {
  const at = sheet.indexOf(`/* ${face} */`);
  if (at < 0) return undefined;
  const block = sheet.slice(at, sheet.indexOf('}', at));
  return /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim() ?? null;
}

/** The stylesheet for these families, from a reader of `<package id>/<file>` in the Fontsource packages. */
export function documentFontFaceCss(
  fonts: readonly DocumentFont[],
  read: (path: string) => string,
): string {
  const rules: string[] = [];
  for (const font of fonts) {
    if (!font.served) continue;
    const { id, styles } = font.served;
    for (const style of styles) {
      const sheet = read(`${id}/${sheetOf(style)}`);
      const [weight, slant] = style.split('-') as [string, string];
      for (const subset of DOCUMENT_FONT_SUBSETS) {
        const face = `${id}-${subset}-${style}`;
        const range = faceRange(sheet, face);
        if (range === undefined) continue;
        rules.push(
          [
            '@font-face {',
            `  font-family: "${font.name}";`,
            `  font-style: ${slant};`,
            `  font-weight: ${weight};`,
            '  font-display: swap;',
            `  src: url("${DOCUMENT_FONT_FILES}/${id}/files/${face}.woff2") format("woff2");`,
            ...(range ? [`  unicode-range: ${range};`] : []),
            '}',
          ].join('\n'),
        );
      }
    }
  }
  return `${[
    '/*',
    ' * The served document fonts (docs/specs/004-interface-design/fonts.md "Served from LiveDoc").',
    ' * Generated by `pnpm fonts:document` (lib/document-fonts/document-font-faces.ts); do not edit.',
    ' */',
    ...rules,
  ].join('\n')}\n`;
}
