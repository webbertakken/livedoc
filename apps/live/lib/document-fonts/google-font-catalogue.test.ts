import { describe, expect, it } from 'vitest';
import {
  FONT_CATEGORIES,
  categoryOfGeneric,
  googleFontAxes,
  googleFontCatalogueOf,
  googleFontsOf,
  loadGoogleFonts,
} from './google-font-catalogue';
import file from './google-fonts.json';

const family = (overrides: Record<string, unknown>) => ({
  family: 'Rubik',
  category: 'Sans Serif',
  popularity: 20,
  trending: 300,
  dateAdded: '2015-06-01',
  fonts: { '400': {}, '700': {} },
  ...overrides,
});

describe('googleFontAxes (fonts.md "More fonts": regular and bold, upright and italic, or the nearest)', () => {
  it('asks for nothing more when the family has only its regular', () => {
    expect(googleFontAxes(['400'])).toBe('');
  });

  it('asks for regular and bold upright', () => {
    expect(googleFontAxes(['100', '400', '700', '900'])).toBe('wght@400;700');
  });

  it('asks for the nearest weights a family has', () => {
    expect(googleFontAxes(['300'])).toBe('wght@300');
    expect(googleFontAxes(['300', '500', '800'])).toBe('wght@300;800');
  });

  it('adds the italics it has', () => {
    expect(googleFontAxes(['400', '400i', '700', '700i'])).toBe(
      'ital,wght@0,400;0,700;1,400;1,700',
    );
    expect(googleFontAxes(['400', '400i'])).toBe('ital,wght@0,400;1,400');
  });

  it('asks for italics alone when a family has no upright', () => {
    expect(googleFontAxes(['400i'])).toBe('ital,wght@1,400');
  });
});

describe('googleFontCatalogueOf (fonts.md "More fonts": the catalogue from Google Fonts metadata)', () => {
  it('keeps name, category, ranks, date and axes, in alphabetical order', () => {
    const catalogue = googleFontCatalogueOf({
      familyMetadataList: [
        family({ family: 'Zilla Slab', category: 'Serif', fonts: { '400': {} } }),
        family({}),
      ],
    });
    expect(catalogue.families).toEqual([
      ['Rubik', 'Sans Serif', 20, 300, '2015-06-01', 'wght@400;700'],
      ['Zilla Slab', 'Serif', 20, 300, '2015-06-01', ''],
    ]);
    expect(catalogue.source).toContain('fonts.google.com/metadata/fonts');
  });

  it('leaves out a family of an unknown category and keeps the first of a repeated name', () => {
    const catalogue = googleFontCatalogueOf({
      familyMetadataList: [family({ category: 'Icons' }), family({}), family({ popularity: 1 })],
    });
    expect(catalogue.families).toHaveLength(1);
    expect(catalogue.families[0]![2]).toBe(20);
  });

  it('leaves out a family of another shape', () => {
    const catalogue = googleFontCatalogueOf({
      familyMetadataList: [
        null,
        3,
        family({ popularity: 'high' }),
        family({ fonts: null }),
        family({}),
      ],
    });
    expect(catalogue.families.map(([name]) => name)).toEqual(['Rubik']);
  });

  it('refuses metadata without a family list', () => {
    expect(() => googleFontCatalogueOf(null)).toThrow(
      '[fonts] google metadata has no familyMetadataList',
    );
    expect(() => googleFontCatalogueOf({})).toThrow(
      '[fonts] google metadata has no familyMetadataList',
    );
  });
});

describe('loadGoogleFonts', () => {
  it('reads the generated file once', async () => {
    const first = loadGoogleFonts();
    expect(loadGoogleFonts()).toBe(first);
    expect((await first).find((f) => f.name === 'Rubik')?.category).toBe('Sans Serif');
  });
});

describe('googleFontsOf', () => {
  it('leaves out a row of another shape', () => {
    expect(
      googleFontsOf({ families: [['Rubik', 'Icons', 1, 1, '2015-01-01', ''], ['Rubik'], [3]] }),
    ).toEqual([]);
  });

  it('reads the tuples as fonts', () => {
    const fonts = googleFontsOf({
      families: [['Rubik', 'Sans Serif', 20, 300, '2015-06-01', 'wght@400;700']],
    });
    expect(fonts).toEqual([
      {
        name: 'Rubik',
        category: 'Sans Serif',
        popularity: 20,
        trending: 300,
        dateAdded: '2015-06-01',
        axes: 'wght@400;700',
      },
    ]);
  });
});

describe('categoryOfGeneric (fonts.md "More fonts": a named family by its generic family)', () => {
  it('maps every generic family', () => {
    expect(categoryOfGeneric('roman')).toBe('Serif');
    expect(categoryOfGeneric('swiss')).toBe('Sans Serif');
    expect(categoryOfGeneric('modern')).toBe('Monospace');
    expect(categoryOfGeneric('script')).toBe('Handwriting');
    expect(categoryOfGeneric('decorative')).toBe('Display');
  });
});

describe('google-fonts.json (generated by pnpm fonts:google)', () => {
  const fonts = googleFontsOf(file);

  it('reads every row', () => {
    expect(fonts).toHaveLength(file.families.length);
  });

  it('holds the catalogue, sorted, unique, each in a known category', () => {
    const names = fonts.map((f) => f.name);
    expect(names.length).toBeGreaterThan(1500);
    expect(names).toEqual([...names].sort((a, b) => a.localeCompare(b, 'en')));
    expect(new Set(names).size).toBe(names.length);
    for (const { category } of fonts) expect(FONT_CATEGORIES).toContain(category);
  });

  it('asks only for axes css2 reads', () => {
    for (const { axes } of fonts)
      expect(axes).toMatch(/^(|wght@\d+(;\d+)?|ital,wght@[01],\d+(;[01],\d+){0,3})$/);
  });
});
