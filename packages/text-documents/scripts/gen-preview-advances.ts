// Writes src/previews/preview-advances.ts: the advance widths of the Inter faces render-png bundles (docs/specs/
// 034-text-documents/agents-and-sync.md "Page previews"), in thousandths of an em, for the characters a preview
// breaks lines over. Reproducible: `pnpm --filter @livedoc/text-documents gen:preview-advances`, from the fonts'
// own tables (then `prettier --write` the file), so the previews break lines by the widths the picture draws them at.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Sfnt } from '@livedoc/pdf-documents/sfnt';

const here = dirname(fileURLToPath(import.meta.url));
const fonts = join(here, '../../render-png/fonts');
const out = join(here, '../src/previews/preview-advances.ts');

// Latin and its extensions, general punctuation, currency signs.
const RANGES: readonly (readonly [number, number])[] = [
  [0x20, 0x24f],
  [0x2010, 0x2044],
  [0x20a0, 0x20bf],
];

function advancesOf(file: string): number[][] {
  const tables = Sfnt.tables(readFileSync(join(fonts, file)));
  const unitsPerEm = new DataView(
    tables.get('head')!.buffer,
    tables.get('head')!.byteOffset,
  ).getUint16(18);
  const advances = Sfnt.advances(tables);
  const characters = Sfnt.characters(tables);
  return RANGES.map(([from, to]) =>
    Array.from({ length: to - from + 1 }, (_, n) => {
      const glyph = characters.get(from + n);
      return glyph === undefined ? 0 : Math.round((advances[glyph] * 1000) / unitsPerEm);
    }),
  );
}

const faces = { regular: advancesOf('Inter-Regular.ttf'), bold: advancesOf('Inter-Bold.otf') };
const rows = (face: number[][]) =>
  face
    .map(
      (widths, n) =>
        `    { from: 0x${RANGES[n][0].toString(16)}, widths: [${widths.join(', ')}] },`,
    )
    .join('\n');

writeFileSync(
  out,
  `// Generated by scripts/gen-preview-advances.ts from render-png's Inter faces: do not edit.
// Each character's advance in thousandths of an em, by range; 0 where the face has no glyph for it.

export type AdvanceRange = { readonly from: number; readonly widths: readonly number[] };

export const PREVIEW_ADVANCES: {
  readonly regular: readonly AdvanceRange[];
  readonly bold: readonly AdvanceRange[];
} = {
  regular: [
${rows(faces.regular)}
  ],
  bold: [
${rows(faces.bold)}
  ],
};
`,
);
console.log(`[gen-preview-advances] wrote ${out}`);
