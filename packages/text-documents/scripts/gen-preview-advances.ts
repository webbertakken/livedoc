// Writes src/previews/preview-advances.ts: the advance widths a page preview breaks lines by (docs/specs/
// 034-text-documents/agents-and-sync.md "Page previews", "Lines"), in thousandths of an em: the Inter faces render-png
// draws with, and the served faces the editor draws the common document fonts in (Arimo for Arial, Tinos for Times
// New Roman, ...), each regular and bold, from their own tables. Reproducible:
// `pnpm --filter @livedoc/text-documents gen:preview-advances`, then `prettier --write` the file.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Sfnt, type SfntTables } from '@livedoc/pdf-documents/sfnt';
import { woffTables } from '@livedoc/pdf-documents/woff';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const inter = join(here, '../../render-png/fonts');
const out = join(here, '../src/previews/preview-advances.ts');

// Latin and its extensions, general punctuation, currency signs.
const RANGES: readonly (readonly [number, number])[] = [
  [0x20, 0x24f],
  [0x2010, 0x2044],
  [0x20a0, 0x20bf],
];

// The served faces whose widths the previews carry: the stand-ins of Office's and Google's usual fonts.
const SERVED = ['Arimo', 'Tinos', 'Cousine', 'Carlito', 'Caladea', 'Roboto'] as const;

const bytes = (path: string) => new Uint8Array(readFileSync(path));

// Each character's advance, thousandths of an em, read from the first face of `faces` that has it; 0 for none.
function advancesOf(faces: readonly SfntTables[]): number[][] {
  const read = faces.map((tables) => ({
    unitsPerEm: new DataView(tables.get('head')!.buffer, tables.get('head')!.byteOffset).getUint16(
      18,
    ),
    advances: Sfnt.advances(tables),
    characters: Sfnt.characters(tables),
  }));
  return RANGES.map(([from, to]) =>
    Array.from({ length: to - from + 1 }, (_, n) => {
      for (const face of read) {
        const glyph = face.characters.get(from + n);
        if (glyph !== undefined) return Math.round((face.advances[glyph] * 1000) / face.unitsPerEm);
      }
      return 0;
    }),
  );
}

// A served face's Latin and Latin Extended files, at a weight.
async function servedFace(family: string, weight: 400 | 700): Promise<SfntTables[]> {
  const id = family.toLowerCase();
  const file = (subset: string) =>
    require.resolve(`@fontsource/${id}/files/${id}-${subset}-${weight}-normal.woff`);
  return Promise.all(['latin', 'latin-ext'].map(async (s) => woffTables(bytes(file(s)))));
}

const faces: Record<string, { regular: number[][]; bold: number[][] }> = {
  Inter: {
    regular: advancesOf([Sfnt.tables(bytes(join(inter, 'Inter-Regular.ttf')))]),
    bold: advancesOf([Sfnt.tables(bytes(join(inter, 'Inter-Bold.otf')))]),
  },
};
for (const family of SERVED)
  faces[family] = {
    regular: advancesOf(await servedFace(family, 400)),
    bold: advancesOf(await servedFace(family, 700)),
  };

const rows = (face: number[][]) =>
  face
    .map((widths, n) => `{ from: 0x${RANGES[n][0].toString(16)}, widths: [${widths.join(', ')}] }`)
    .join(', ');

writeFileSync(
  out,
  `// Generated by scripts/gen-preview-advances.ts from render-png's Inter faces and the served document faces: do not
// edit. Each character's advance in thousandths of an em, by range; 0 where the face has no glyph for it.

export type AdvanceRange = { readonly from: number; readonly widths: readonly number[] };

export type FaceAdvances = { readonly regular: readonly AdvanceRange[]; readonly bold: readonly AdvanceRange[] };

/** By family: Inter, which the previews draw in, and the served faces the editor draws common fonts in. */
export const PREVIEW_ADVANCES: Readonly<Record<string, FaceAdvances>> = {
${Object.entries(faces)
  .map(
    ([family, face]) =>
      `  ${family}: { regular: [${rows(face.regular)}], bold: [${rows(face.bold)}] },`,
  )
  .join('\n')}
};
`,
);
console.log(`[gen-preview-advances] wrote ${out}: ${Object.keys(faces).join(', ')}`);
