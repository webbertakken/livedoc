export const ODF_LIVEDOC_PREFIX = 'ORG.LIVEDOC.';

const GOOGLE_NAMES: ReadonlyMap<string, string> = new Map(
  Object.entries(ODF_FUNCTION_NAMES).map(([google, odf]) => [odf, google]),
);

/** A function's name as an ODF file writes it, from its name as typed (any case). */
export function odfFunctionName(name: string): string {
  const upper = name.toUpperCase();
  if (GOOGLE_ONLY_FUNCTIONS.has(upper)) return `${ODF_LIVEDOC_PREFIX}${upper}`;
  return ODF_FUNCTION_NAMES[upper] ?? name;
}

/** A function's name as Google writes it, from an ODF file's. */
export function googleFunctionName(name: string): string {
  const upper = name.toUpperCase();
  if (upper.startsWith(ODF_LIVEDOC_PREFIX)) return upper.slice(ODF_LIVEDOC_PREFIX.length);
  return GOOGLE_NAMES.get(upper) ?? name;
}
