// Generates the tables of Chinese, Japanese and Korean (docs/specs/035-pdf-documents/marks.md "Laying out"): each
// region measured as one face, read from the very slices LiveDoc serves (mark-face-region-data.ts, small, with the
// rest of the table), and which slice holds each character (mark-face-slices-<region>.ts, loaded only where a region
// is set). A character is its region's where the first slice whose range holds it has it.
import {
  MARK_FACE_REGIONS,
  markFaceFile,
  markFaceId,
  type MarkFaceRegion,
} from '../mark-face-families';
import { sliceIndex } from './region-slices';
import { Sfnt } from './sfnt';
import { woffTables } from './woff';

type Read = (file: string) => Promise<Uint8Array<ArrayBuffer>>;

const GENERATED =
  '// Generated by `pnpm --filter @livedoc/pdf-documents faces:generate` (engine/mark-face-region-table.ts); do not edit.';

/** A region's numbered slices, in order, each with its unicode range. */
async function slicesOf(read: Read, pkg: string) {
  const ranges = JSON.parse(new TextDecoder().decode(await read(`${pkg}/unicode.json`))) as Record<
    string,
    string
  >;
  return Object.keys(ranges)
    .filter((key) => /^\[\d+\]$/.test(key))
    .map((key) => ({ slice: key.slice(1, -1), range: ranges[key]! }))
    .sort((a, b) => Number(a.slice) - Number(b.slice));
}

/** Advances in the order of their characters, as runs: each how many alike, then their advance. */
function advanceRuns(advances: readonly number[]): number[] {
  const out: number[] = [];
  for (const advance of advances)
    if (out.at(-1) === advance) out[out.length - 2]! += 1;
    else out.push(1, advance);
  return out;
}

/** A region measured: each character it has and its advance, and the missing glyph's advance. */
async function measured(read: Read, pkg: string) {
  const slices = await slicesOf(read, pkg);
  const faces = new Map<string, { characters: Map<number, number>; advances: number[] }>();
  let missing = 0;
  for (const { slice } of slices) {
    const tables = await woffTables(await read(markFaceFile(pkg, slice, 400)));
    const { unitsPerEm } = Sfnt.metrics(tables);
    const per = (units: number) => Math.round((units * 1000) / unitsPerEm);
    const advances = Sfnt.advances(tables).map(per);
    missing ||= advances[0]!;
    faces.set(slice, { characters: new Map(Sfnt.characters(tables)), advances });
  }
  // The bake cuts a run by the same index (region-slices.ts), so a character measured is set in the slice measured.
  const advances = new Map<number, number>();
  for (const [code, { slice }] of sliceIndex(slices)) {
    const face = faces.get(slice)!;
    const glyph = face.characters.get(code);
    if (glyph !== undefined) advances.set(code, face.advances[glyph]!);
  }
  return { advances, missing };
}

/** Code points as runs: each its gap after the run before it ends, then its length. */
function rangesFrom(codes: readonly number[]): number[] {
  const out: number[] = [];
  let end = 0;
  for (const code of codes) {
    if (out.length > 0 && code === end) out[out.length - 1]! += 1;
    else out.push(code - end, 1);
    end = code + 1;
  }
  return out;
}

/** The source of mark-face-region-data.ts. */
export async function markFaceRegionDataSource(read: Read): Promise<string> {
  const lines: string[] = [];
  for (const { region, family, package: pkg } of MARK_FACE_REGIONS) {
    const { advances, missing } = await measured(read, pkg);
    const codes = [...advances.keys()].sort((a, b) => a - b);
    const runs = advanceRuns(codes.map((code) => advances.get(code)!));
    lines.push(
      `  {\n    id: '${pkg}-400',\n    family: '${family}',\n    region: '${region}',\n    missing: ${missing},\n` +
        `    ranges: ${JSON.stringify(rangesFrom(codes))},\n    advances: ${JSON.stringify(runs)},\n  },`,
    );
  }
  return [
    GENERATED,
    '// Chinese, Japanese and Korean as one face a region (docs/specs/035-pdf-documents/marks.md "Laying out"): the',
    '// characters its slices hold, as runs of a gap after the run before and a length; and their advances in that',
    '// order, in thousandths of the size, as runs of how many alike and their advance. Pure data, read from the',
    '// Fontsource slices LiveDoc serves (SIL OFL 1.1).',
    "import type { MarkFaceRegion } from './mark-face-families';",
    '',
    'export type MarkFaceRegionData = {',
    '  readonly id: string;',
    '  readonly family: string;',
    '  readonly region: MarkFaceRegion;',
    '  readonly missing: number;',
    '  readonly ranges: readonly number[];',
    '  readonly advances: readonly number[];',
    '};',
    '',
    'export const MARK_FACE_REGION_DATA: readonly MarkFaceRegionData[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

/** The source of mark-face-slices-<region>.ts: each slice's face, file and range, its file as an asset. */
export async function markFaceSlicesSource(read: Read, region: MarkFaceRegion): Promise<string> {
  const { package: pkg } = MARK_FACE_REGIONS.find((each) => each.region === region)!;
  const slices = (await slicesOf(read, pkg)).map(({ slice, range }) => {
    const file = markFaceFile(pkg, slice, 400);
    return (
      `  {\n    id: '${markFaceId(pkg, slice, 400)}',\n    file: '${file}',\n    range: '${range}',\n` +
      `    url: () => new URL('@fontsource/${file}', import.meta.url),\n  },`
    );
  });
  return [
    GENERATED,
    `// The slices of ${pkg} (docs/specs/035-pdf-documents/marks.md "Laying out", "Loading"): which holds each`,
    "// character, as its unicode range, and its file as a hashed asset of LiveDoc's own origin. Loaded only by a bake",
    '// or a surface that sets the region.',
    "import type { MarkFaceSlice } from './mark-face-families';",
    '',
    'export const MARK_FACE_SLICES: readonly MarkFaceSlice[] = [',
    ...slices,
    '];',
    '',
  ].join('\n');
}
