// Generates mark-face-data.ts (docs/specs/035-pdf-documents/marks.md "Laying out"): each mark face's advance for each
// character it has within its subset's range, read from the very WOFF files LiveDoc serves, so the surface and the
// bake measure a mark's words alike with no font loaded. `read` answers a file within the Fontsource packages. And
// mark-face-urls.ts ("Loading"): each face's file as an asset of the app that bundles the engine.
import { MARK_FACE_FAMILIES, markFaceFile, markFaceId } from '../mark-face-families';
import { Sfnt } from './sfnt';
import { woffTables } from './woff';

type Read = (file: string) => Promise<Uint8Array<ArrayBuffer>>;

/** A CSS unicode-range's code points, as inclusive pairs. */
export const rangesOf = (range: string): (readonly [number, number])[] =>
  range.split(',').map((part) => {
    const [first, last] = part.trim().replace(/^U\+/i, '').split('-');
    return [parseInt(first!, 16), parseInt(last ?? first!, 16)] as const;
  });

/** Code points and their advances as runs: each a first code point, then the advance of it and each that follows. */
function runsOf(advances: ReadonlyMap<number, number>): number[][] {
  const runs: number[][] = [];
  let last = -2;
  for (const code of [...advances.keys()].sort((a, b) => a - b)) {
    if (code !== last + 1) runs.push([code]);
    runs.at(-1)!.push(advances.get(code)!);
    last = code;
  }
  return runs;
}

async function faceOf(read: Read, pkg: string, subset: string, weight: number, range: string) {
  const tables = await woffTables(await read(markFaceFile(pkg, subset, weight)));
  const { unitsPerEm } = Sfnt.metrics(tables);
  const glyphAdvances = Sfnt.advances(tables);
  const per = (units: number) => Math.round((units * 1000) / unitsPerEm);
  const within = rangesOf(range);
  const advances = new Map<number, number>();
  for (const [code, glyph] of Sfnt.characters(tables))
    if (within.some(([first, last]) => code >= first && code <= last))
      advances.set(code, per(glyphAdvances[glyph]!));
  return {
    id: markFaceId(pkg, subset, weight),
    file: markFaceFile(pkg, subset, weight),
    weight,
    missing: per(glyphAdvances[0]!),
    runs: runsOf(advances),
  };
}

/** The source of mark-face-data.ts. */
export async function markFaceDataSource(read: Read): Promise<string> {
  const faces = [];
  for (const { package: pkg, subsets, weights, family } of MARK_FACE_FAMILIES) {
    const ranges = JSON.parse(
      new TextDecoder().decode(await read(`${pkg}/unicode.json`)),
    ) as Record<string, string>;
    for (const weight of weights)
      for (const subset of subsets)
        faces.push({
          family,
          subset,
          ...(await faceOf(read, pkg, subset, weight, ranges[subset]!)),
          range: ranges[subset]!,
        });
  }
  const lines = faces.map(
    (face) =>
      `  {\n    id: '${face.id}',\n    file: '${face.file}',\n    family: '${face.family}',\n    subset: '${face.subset}',\n` +
      `    weight: ${face.weight},\n    range: '${face.range}',\n    missing: ${face.missing},\n` +
      `    runs: ${JSON.stringify(face.runs)},\n  },`,
  );
  return [
    '// Generated by `pnpm --filter @livedoc/pdf-documents faces:generate` (engine/mark-face-table.ts); do not edit.',
    '// Each mark face (docs/specs/035-pdf-documents/marks.md "Laying out"): its range, its missing glyph\'s advance,',
    '// and the advance of each character it has, in thousandths of the size, as runs: a first code point, then the',
    '// advance of it and of each that follows. Pure data, read from the Fontsource files LiveDoc serves (SIL OFL 1.1).',
    '',
    'export type MarkFaceData = {',
    '  readonly id: string;',
    '  /** Its file within the Fontsource packages. */',
    '  readonly file: string;',
    '  readonly family: string;',
    '  readonly subset: string;',
    '  readonly weight: 400 | 700;',
    '  readonly range: string;',
    '  readonly missing: number;',
    '  readonly runs: readonly (readonly number[])[];',
    '};',
    '',
    'export const MARK_FACE_DATA: readonly MarkFaceData[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

/** The source of mark-face-urls.ts, from the generated table's files. */
export function markFaceUrlsSource(files: readonly string[]): string {
  return [
    '// Generated by `pnpm --filter @livedoc/pdf-documents faces:generate` (engine/mark-face-table.ts); do not edit.',
    '// Each mark face\'s file (docs/specs/035-pdf-documents/marks.md "Loading") as a hashed asset of the app that',
    "// bundles the engine, fetched from LiveDoc's own origin only when a bake's marks need it.",
    '',
    'export const MARK_FACE_URLS: Readonly<Record<string, () => URL>> = {',
    ...files.map((file) => `  '${file}': () => new URL('@fontsource/${file}', import.meta.url),`),
    '};',
    '',
  ].join('\n');
}
